def emulate(cfg, asm_funcs, cflogpath):
    breakpoints = ['0x8040382']

    f = "emulate.log"
    debug = os.environ.get('SABRE_DEBUG', '1') != '0'
    emulator = Emulator(arch=cfg.arch, mode=f'data-log', debugFile=f, debug=debug, datalogpath=cflogpath)

    addr = cfg.head
    print(f"Start_addr: {addr}")

    #a = input()
    to_continue = True

    while to_continue: #len(cfg.nodes[addr].successors) != 0:
        if addr not in cfg.nodes:
            print(f"\nERROR: no CFG node at branch target {addr}")
            sys.exit(1)
        for inst in cfg.nodes[addr].instr_addrs:
            print(f"{inst.addr}\t{inst.instr}\t{inst.arg}", end='\r')
            valid = emulator.step(inst)
            if getattr(emulator, 'datalog_exhausted', False):
                to_continue = False
                break
        if not to_continue:
            break

        if cfg.nodes[addr].type == 'cond':
            if cfg.arch.type == 'armv8-m33':
                full_arg ='0x'+inst.arg.split(' ')[0]
            else:
                offset = inst.arg.split(' ')[0].replace('$', '')
                full_arg = emulator.evaluate_expression(f"{int(inst.addr,16)}{offset}")
                full_arg = hex(int(full_arg))
            adj_arg = hex(int(inst.addr,16)+cfg.arch.regular_instr_size)

            dest = emulator.get_cond_branch_dest(inst)
            addr = cfg.nodes[addr].successors[dest]
            
        elif cfg.nodes[addr].type == 'call' and cfg.arch.instrumentation_handle in inst.arg:
            addr = cfg.nodes[addr].adj_instr
        elif cfg.nodes[addr].type == 'ret':
            if 'lr' in inst.arg: #bx lr
                addr = hex(int(emulator.get_reg('lr')))
            elif 'pc' in inst.arg: #pop pc
                addr = hex(int(emulator.get_reg('pc')))
            else:
                print('\n')
                print(f"not sure how you got here... \n {inst}")
                sys.exit(1)
        else: ## not cond branch
            addr = cfg.nodes[addr].successors[0]
        # print(f"[emulate] Next node: {addr}")

        if cfg.arch.type == 'armv8-m33':
            if addr == cfg.arch.ret_to_NS:
                to_continue = False
        else:
            print("TO DO (why are you doing this in openmsp430)")
            sys.exit(1)

    print('\n')
    used_bytes = emulator.datalog_byte_idx
    total_bytes = len(emulator.datalog_bytes)
    consumed_lines = 0
    line_end = 0
    for line in emulator.datalog:
        line_end += len(line) // 2
        if used_bytes < line_end:
            break
        consumed_lines += 1
    print(f"Used {consumed_lines}/{len(emulator.datalog)} datalog inputs")
    print(f"Used {used_bytes}/{total_bytes} data-log bytes")
    if used_bytes != total_bytes:
        print(f"FAIL: {total_bytes - used_bytes} data-log byte(s) unconsumed")
        sys.exit(1)
    print("PASS: all data-log inputs consumed")

def main():
    ## build cfg and save cfg and asm files
    cfg, asm_funcs, cflog = setup()

    ## step through trace
    emulate(cfg, asm_funcs, cflog)

    

if __name__ == '__main__':
    main()